#!/usr/bin/env python3
"""Check public source files for encoding corruption and machine-specific paths."""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

TEXT_EXTENSIONS = {
    ".md", ".txt", ".cpp", ".h", ".cs", ".py", ".ps1", ".sh", ".bat",
    ".usf", ".ush", ".ini", ".json", ".xml", ".yml", ".yaml",
    ".uplugin", ".uproject", ".toml",
}
SPECIAL_NAMES = {".gitattributes", ".gitignore", ".editorconfig", "LICENSE"}

# UTF-8 text that was accidentally decoded as Windows-1252.
# Unicode escapes keep this check from detecting its own pattern definitions.
BAD_FRAGMENTS = (
    "\u00e2\u20ac\u201c", "\u00e2\u20ac\u201d", "\u00e2\u2020\u2019",
    "\u00e2\u201d", "\u00c3\u00d7", "\u00c2\u00a0",
    "\u00ef\u00bb\u00bf", "\ufffd",
)
LOCAL_PATH = re.compile(r"(?i)[A-Z]:[\\/](?:Users|CUSTOMGPT|UnrealProjects|NR6|RND5_6|Epicgames)|/(?:Users|home)/[^/\s]+")
AI_MARKER = re.compile(
    r"(?i)\b(?:as an (?:AI )?language model|"
    r"generated with (?:claude|codex) code|"
    r"generated by (?:chatgpt|gemini))\b"
)


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    output = subprocess.check_output(["git", "ls-files", "-z"], cwd=root)
    tracked = [Path(s.decode("utf-8")) for s in output.split(b"\0") if s]
    checked = 0
    problems = []

    for relative in tracked:
        if relative.suffix.lower() not in TEXT_EXTENSIONS and relative.name not in SPECIAL_NAMES:
            continue
        checked += 1
        try:
            content = (root / relative).read_bytes().decode("utf-8-sig")
        except UnicodeDecodeError as exc:
            problems.append(f"{relative}: invalid UTF-8: {exc}")
            continue

        for number, line in enumerate(content.splitlines(), 1):
            reason = (
                "encoding corruption" if any(fragment in line for fragment in BAD_FRAGMENTS)
                else "machine-specific absolute path" if LOCAL_PATH.search(line)
                else "unreviewed generated-text marker" if AI_MARKER.search(line)
                else None
            )
            if reason:
                problems.append(f"{relative}:{number}: {reason}: {line.strip()[:120]}")

    for problem in problems:
        print(f"ERROR: {problem}")
    if problems:
        print(f"Public source check failed: {len(problems)} finding(s) in {checked} text files.")
        return 1

    print(f"Public source check passed: {checked} tracked text files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
